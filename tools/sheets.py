"""Preflight and code generation for the design sheets.

python tools/sheets.py preflight   -> lists every unfilled cell and unresolved reference (exit 1 if any)
python tools/sheets.py gen         -> preflight, then writes src/gen/sheets.h (one struct per row)
"""
import json, sys, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHEETS = os.path.join(ROOT, "sheets")
OUT = os.path.join(ROOT, "src", "gen", "sheets.h")


def load():
    s = {}
    for f in sorted(os.listdir(SHEETS)):
        if f.endswith(".json"):
            with open(os.path.join(SHEETS, f), encoding="utf-8") as fh:
                s[f[:-5]] = json.load(fh)
    return s


def tables(s):
    """Yield (name, columns, rows) for every table, including nested ones."""
    for name, sh in s.items():
        yield name, sh["columns"], sh["rows"]
        for k, v in sh.items():
            if isinstance(v, dict) and "columns" in v and "rows" in v:
                yield name + "." + k, v["columns"], v["rows"]


def preflight(s):
    problems = []
    for name, cols, rows in tables(s):
        for i, r in enumerate(rows):
            rid = r.get("key", i)
            for c in cols:
                v = r.get(c)
                if v is None or (isinstance(v, str) and v.strip() == "") or (isinstance(v, list) and not v and c not in ("excludedObjectIds", "foeIds", "foeModels")):
                    problems.append(f"{name}[{rid}].{c}: unfilled")
            for c in r:
                if c not in cols:
                    problems.append(f"{name}[{rid}].{c}: not a column of {name}")
        keys = [r.get("key") for r in rows if "key" in r]
        if len(keys) != len(set(keys)):
            problems.append(f"{name}: duplicate keys")

    def keyset(table):
        for n, c, rows in tables(s):
            if n == table:
                return {r["key"] for r in rows}
        return set()

    units = keyset("units")
    arenas = keyset("encounters.arenas")
    for r in s["magic"]["rows"]:
        if r["target"] not in ("enemy", "party"):
            problems.append(f"magic[{r['key']}].target: {r['target']} not enemy/party")
    for r in s["encounters"]["rows"]:
        if r["arena"] not in arenas:
            problems.append(f"encounters[{r['key']}].arena -> {r['arena']}: no such arena")
    for r in s["encounters"]["arenas"]["rows"]:
        for f in r["foes"]:
            if f not in units:
                problems.append(f"encounters.arenas[{r['key']}].foes -> {f}: no such unit")
    for r in s["commands"]["rows"]:
        if r["kind"] not in ("attack", "submenu_magic", "submenu_tech", "submenu_items", "defend", "escape", "party"):
            problems.append(f"commands[{r['key']}].kind: {r['kind']} has no implementation")
    for r in s["commands"]["rows"]:
        if r["who"] not in ("sora", "partner", "both"):
            problems.append(f"commands[{r['key']}].who: {r['who']}")
    for r in s["units"]["rows"]:
        if r["side"] == "enemy" and r["actWindowSec"] <= 0:
            problems.append(f"units[{r['key']}].actWindowSec must be > 0 for enemies")
    sysk = {r["key"] for r in s["systems"]["rows"]}
    for need in ("groupPlayer", "groupMob", "groupBoss", "encounterMeterMin", "encounterMeterMax"):
        if need not in sysk:
            problems.append(f"systems: missing {need}")
    return problems


def cstr(v):
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def num(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, float):
        return repr(v) + "f"
    if isinstance(v, str) and v.startswith("0x"):
        return v
    return str(v)


def gen(s):
    L = ["// Generated by tools/sheets.py from sheets/*.json. Edit the sheets, not this file.", "#pragma once", "#include <cstdint>", "namespace sheets {", ""]
    hk = s["hooks"]["rows"]
    L.append("// hooks.json")
    for r in hk:
        if r["rva"].startswith("0x"):
            L.append(f"constexpr uintptr_t RVA_{r['key']} = {r['rva']};")
            if r["kind"] == "func":
                b = bytes.fromhex(r["signature"])
                L.append(f"constexpr uint8_t SIG_{r['key']}[16] = {{{', '.join(hex(x) for x in b)}}};")
    L.append("")
    L.append("// systems.json")
    for r in s["systems"]["rows"]:
        v = r["value"]
        if isinstance(v, list):
            L.append(f"constexpr uint32_t {r['key']}[] = {{{', '.join(str(x) for x in v)}}};")
        elif isinstance(v, float):
            L.append(f"constexpr float {r['key']} = {num(v)};")
        else:
            L.append(f"constexpr int {r['key']} = {v};")
    L.append("struct TickRow { int agiMin, agiMax, tick; };")
    L.append("constexpr TickRow ctbTickTable[] = {" + ", ".join(f"{{{r['agilityMin']},{r['agilityMax']},{r['tickSpeed']}}}" for r in s["systems"]["ctbTickTable"]["rows"]) + "};")
    L.append("")
    L.append("// units.json")
    L.append("struct Unit { const char* key; const char* name; bool enemy; bool matchPlayer; bool matchModel; uint32_t objectId; const char* kh2Model; int agility; float actWindowSec; float magicResist; const char* weakness; const char* scanText; bool inEncounters; };")
    L.append("constexpr Unit units[] = {")
    for r in s["units"]["rows"]:
        L.append(f"  {{{cstr(r['key'])}, {cstr(r['name'])}, {num(r['side']=='enemy')}, {num(r['match']=='objentryType')}, {num(r['match']=='model')}, {r['objectId']}, {cstr(r['kh2Model'])}, {r['agility']}, {num(float(r['actWindowSec']))}, {num(float(r['magicResist']))}, {cstr(r['weakness'])}, {cstr(r['scanText'])}, {num(r['inEncounters'])}}},")
    L.append("};")
    L.append("")
    L.append("// magic.json")
    L.append("struct Magic { const char* key; const char* names[3]; uint32_t saveOffset; uint16_t cmd[3]; bool targetEnemy; float castReach; float castWindowSec; const char* description; };")
    L.append("constexpr Magic magic[] = {")
    for r in s["magic"]["rows"]:
        L.append(f"  {{{cstr(r['key'])}, {{{cstr(r['name1'])}, {cstr(r['name2'])}, {cstr(r['name3'])}}}, {r['saveOffset']}, {{{r['cmd1']}, {r['cmd2']}, {r['cmd3']}}}, {num(r['target']=='enemy')}, {num(float(r['castReach']))}, {num(float(r['castWindowSec']))}, {cstr(r['description'])}}},")
    L.append("};")
    L.append("")
    L.append("// partnerMoves.json")
    L.append("struct PartnerMove { const char* key; const char* partnerModel; bool technique; const char* name; uint16_t abilityId; uint32_t abilityList; bool targetEnemy; float windowSec; uint16_t moveMotions[4]; const char* description; };")
    L.append("constexpr PartnerMove partnerMoves[] = {")
    for r in s["partnerMoves"]["rows"]:
        mm = (r['moveMotions'] + [0, 0, 0, 0])[:4]
        L.append(f"  {{{cstr(r['key'])}, {cstr(r['partnerModel'])}, {num(r['kind']=='technique')}, {cstr(r['name'])}, {r['abilityId']}, {r['abilityList']}, {num(r['target']=='enemy')}, {num(float(r['windowSec']))}, {{{', '.join(str(x) for x in mm)}}}, {cstr(r['description'])}}},")
    L.append("};")
    L.append("")
    L.append("// battleMaps.json")
    L.append("struct BattleMap { const char* key; uint8_t world, room; uint16_t btlProgram, door; float triggerX, triggerY, triggerZ, spotX, spotY, spotZ, dirX, dirZ; int waves; const char* roomName; };")
    L.append("constexpr BattleMap battleMaps[] = {")
    for r in s["battleMaps"]["rows"]:
        L.append(f"  {{{cstr(r['key'])}, {r['world']}, {r['room']}, {r['btlProgram']}, {r['door']}, {num(float(r['triggerX']))}, {num(float(r['triggerY']))}, {num(float(r['triggerZ']))}, {num(float(r['spotX']))}, {num(float(r['spotY']))}, {num(float(r['spotZ']))}, {num(float(r['dirX']))}, {num(float(r['dirZ']))}, {r['waves']}, {cstr(r['roomName'])}}},")
    L.append("};")
    L.append("")
    L.append("// enemyNames.json")
    L.append("struct EnemyName { uint32_t objectId; const char* name; };")
    L.append("constexpr EnemyName enemyNames[] = {")
    for r in s["enemyNames"]["rows"]:
        L.append(f"  {{{r['objectId']}, {cstr(r['name'])}}},")
    L.append("};")
    L.append("")
    L.append("// commands.json")
    L.append("struct Command { const char* key; const char* label; int order; const char* who; const char* kind; int ctbRank; float windowSec; bool encounterOnly; const char* description; };")
    L.append("constexpr Command commands[] = {")
    for r in sorted(s["commands"]["rows"], key=lambda r: r["order"]):
        L.append(f"  {{{cstr(r['key'])}, {cstr(r['label'])}, {r['order']}, {cstr(r['who'])}, {cstr(r['kind'])}, {r['ctbRank']}, {num(float(r['windowSec']))}, {num(r['encounterOnly'])}, {cstr(r['description'])}}},")
    L.append("};")
    L.append("")
    L.append("// items.json")
    L.append("struct Item { const char* key; const char* name; uint32_t saveOffset; uint16_t cmdId; float hp, mp; bool party; const char* description; };")
    L.append("constexpr Item items[] = {")
    for r in s["items"]["rows"]:
        L.append(f"  {{{cstr(r['key'])}, {cstr(r['name'])}, {r['saveOffset']}, {r['cmdId']}, {num(float(r['hp']))}, {num(float(r['mp']))}, {num(r['party'])}, {cstr(r['description'])}}},")
    L.append("};")
    L.append("")
    L.append("// encounters.json")
    ar = s["encounters"]["arenas"]["rows"]
    L.append("struct Arena { const char* key; uint8_t world, room; uint16_t btlProgram; uint16_t door; float triggerX, triggerY, triggerZ; };")
    L.append("constexpr Arena arenas[] = {")
    for r in ar:
        L.append(f"  {{{cstr(r['key'])}, {r['world']}, {r['room']}, {r['btlProgram']}, {r['door']}, {num(float(r['triggerX']))}, {num(float(r['triggerY']))}, {num(float(r['triggerZ']))}}},")
    L.append("};")
    idx = {r["key"]: i for i, r in enumerate(ar)}
    L.append("struct FieldRoom { const char* key; uint8_t world, room; const char* roomName; bool field; int arena; };")
    L.append("constexpr FieldRoom fieldRooms[] = {")
    for r in s["encounters"]["rows"]:
        L.append(f"  {{{cstr(r['key'])}, {r['world']}, {r['room']}, {cstr(r['roomName'])}, {num(r['field'])}, {idx[r['arena']]}}},")
    L.append("};")
    L.append("")
    L.append("} // namespace sheets")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(L) + "\n")


if __name__ == "__main__":
    s = load()
    p = preflight(s)
    total = sum(len(rows) * len(cols) for _, cols, rows in tables(s))
    print(f"preflight: {total} cells across {sum(1 for _ in tables(s))} tables, {len(p)} problems")
    for x in p:
        print("  -", x)
    if p:
        sys.exit(1)
    if len(sys.argv) > 1 and sys.argv[1] == "gen":
        gen(s)
        print("wrote", OUT)
